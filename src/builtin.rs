//! Firmware images embedded in the binary.
//!
//! The list of what gets embedded lives in `firmware/firmwares.json` and is managed
//! with `scripts/firmware.sh`; `build.rs` generates the table below from it. The images
//! are
//! unmodified `.fwsc` update packages mirrored by
//! [The FM-1 Firmware Hub](https://thefirmwarehub.com/), plus M-VAVE's official package that
//! ships with the FM1 Open development kit. The tags are the hub's categories (`kind`)
//! plus its vintage/beta flags; the first tag is the group the dropdowns show a firmware
//! under. See `firmware/README.md` for sources and licences.

pub struct BuiltinFirmware {
    pub name: &'static str,
    pub version: &'static str,
    pub file: &'static str,
    pub sha256: &'static str,
    /// Comma-separated hub tags: the category (`kind`) first, then any further kinds
    /// and the vintage/beta flags.
    pub tags: &'static str,
    /// One-paragraph description from the hub catalog; empty for packages the hub
    /// doesn't list (M-VAVE's own).
    pub description: &'static str,
    /// Author per the hub catalog.
    pub byline: &'static str,
    /// Target device: "fm-1" or "smk37-pro"; empty when unknown.
    pub device: &'static str,
    pub bytes: &'static [u8],
}

impl BuiltinFirmware {
    pub fn label(&self) -> String {
        format!("{} {}", self.name, self.version)
    }
}

/// The embedded firmware table, generated by build.rs from `firmware/firmwares.json`.
pub const BUILTINS: &[BuiltinFirmware] = include!(concat!(env!("OUT_DIR"), "/builtins.rs"));

