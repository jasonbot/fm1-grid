//! Firmware images embedded in the binary.
//!
//! The list of what gets embedded lives in `firmware/manifest.txt` and is managed with
//! `scripts/firmware.sh`; `build.rs` generates the table below from it. The images are
//! unmodified `.fwsc` update packages mirrored by
//! [The FM-1 Firmware Hub](https://thefirmwarehub.com/), plus M-VAVE's official package that
//! ships with the FM1 Open development kit. See `firmware/README.md` for sources and
//! licences.

pub struct BuiltinFirmware {
    pub name: &'static str,
    pub version: &'static str,
    pub file: &'static str,
    pub sha256: &'static str,
    pub bytes: &'static [u8],
}

impl BuiltinFirmware {
    pub fn label(&self) -> String {
        format!("{} {}", self.name, self.version)
    }
}

/// The embedded firmware table, generated by build.rs from `firmware/manifest.txt`.
pub const BUILTINS: &[BuiltinFirmware] = include!(concat!(env!("OUT_DIR"), "/builtins.rs"));
